/** Text for a template in a language; undefined for EN (caller uses the English template). */
export function translate(type: string, lang: string, flight: string, gate: string): string | undefined {
  return T[type]?.[lang]?.(flight, gate);
}

/** True if this browser has a voice for the language (so speech will not silently use the wrong accent). */
export function hasVoice(lang: string): boolean {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return false;
  const code = LANG_BCP47[lang]?.split("-")[0];
  return window.speechSynthesis.getVoices().some(v => v.lang.toLowerCase().startsWith(code));
}
